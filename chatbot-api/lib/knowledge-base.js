/**
 * キーワードでチャンクをスコアリングして上位N件を返す（BM25ライク）
 * @param {string} query - ユーザーの質問
 * @param {number} topN - 返すチャンク数
 * @returns {string} 結合されたコンテキスト文字列
 */
function retrieveContext(query, topN = 4) {
  const words = query
    .toLowerCase()
    .replace(/[。、！？!?,]/g, ' ')
    .split(/\s+/)
    .filter(w => w.length > 1);

  const scored = KNOWLEDGE_CHUNKS.map(chunk => {
    const combined = (chunk.tags.join(' ') + ' ' + chunk.text).toLowerCase();
    let score = 0;
    for (const w of words) {
      // タグに含まれるキーワードは高スコア
      if (chunk.tags.some(t => t.toLowerCase().includes(w) || w.includes(t.toLowerCase()))) {
        score += 3;
      }
      // テキストに含まれるキーワードは1点
      const count = (combined.match(new RegExp(w, 'g')) || []).length;
      score += count;
    }
    return { chunk, score };
  });

  scored.sort((a, b) => b.score - a.score);
  const top = scored.slice(0, topN).filter(s => s.score > 0);

  if (top.length === 0) {
    // スコア0のときも最低限の基本情報を返す
    return KNOWLEDGE_CHUNKS.find(c => c.id === 'basic-info').text;
  }

  return top.map(s => s.chunk.text).join('\n\n---\n\n');
}

